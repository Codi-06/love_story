// ==== Хранилище ====
const STORAGE_KEY = "envelopes_opened_v101";
let openedSet = new Set(JSON.parse(localStorage.getItem(STORAGE_KEY) || "[]"));

// ==== DOM ====
const container = document.getElementById("envelopesContainer");
const modal = document.getElementById("modal");
const modalText = document.getElementById("modalText");
const openedCountEl = document.getElementById("openedCount");
const bgMusic = document.getElementById("bgMusic");

// ==== Рендер конвертов ====
function renderEnvelopes() {
  const frag = document.createDocumentFragment();
  for (let i = 0; i < allReasons.length; i++) {
    const env = document.createElement("div");
    env.className = "envelope";
    env.dataset.index = i;
    if (openedSet.has(i)) env.classList.add("opened");

    const num = document.createElement("span");
    num.className = "num";
    num.textContent = i + 1;

    const heart = document.createElement("span");
    heart.className = "heart-mark";
    heart.textContent = "❤️";

    env.appendChild(num);
    env.appendChild(heart);
    frag.appendChild(env);
  }
  container.appendChild(frag);
  updateCounter();
}

function updateCounter() {
  openedCountEl.textContent = openedSet.size;
}

// ==== Клик по конверту ====
container.addEventListener("click", (e) => {
  const env = e.target.closest(".envelope");
  if (!env) return;
  const idx = Number(env.dataset.index);

  modalText.textContent = allReasons[idx];
  modal.classList.add("show");

  if (!openedSet.has(idx)) {
    openedSet.add(idx);
    env.classList.add("opened");
    localStorage.setItem(STORAGE_KEY, JSON.stringify([...openedSet]));
    updateCounter();
  }
});

// ==== Закрытие модала ====
document.querySelector(".close").onclick = () => modal.classList.remove("show");
modal.addEventListener("click", (e) => {
  if (e.target === modal) modal.classList.remove("show");
});

// ==== МУЗЫКА: всегда играет, без кнопки ====
bgMusic.volume = 0.5;

function startMusic() {
  const promise = bgMusic.play();
  if (promise !== undefined) {
    promise.catch(() => {
      // Браузер заблокировал автозапуск — включим при первом касании
    });
  }
}

// Пытаемся запустить сразу
startMusic();

// При загрузке страницы
window.addEventListener("load", startMusic);

// Если браузер заблокировал — включаем при первом клике/касании/кнопке
function enableMusicOnFirstInteraction() {
  if (bgMusic.paused) {
    bgMusic.play().catch(() => {});
  }
}
document.addEventListener("click", enableMusicOnFirstInteraction);
document.addEventListener("touchstart", enableMusicOnFirstInteraction);
document.addEventListener("keydown", enableMusicOnFirstInteraction);

// ==== Старт ====
renderEnvelopes();